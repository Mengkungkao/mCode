"""Starter files for new projects, in each tool's own layout.

* Arduino CLI: ``<slug>/<slug>.ino`` (the folder and sketch names must
  match), ``app_logic.h``, ``sketch.yaml`` with the board's FQBN.
* PlatformIO: ``platformio.ini``, ``src/``, ``include/``, ``lib/``,
  ``test/`` with a Unity test that runs on the computer (``pio test -e
  native``) for boards whose logic is plain C++.
* ESP-IDF: ``CMakeLists.txt``, ``main/``, ``sdkconfig.defaults``.
* Make: ``Makefile``, ``src/``, ``include/``, ``test/``.

Every project also gets ``README.md`` and ``docs/WIRING.md``. The starter
firmware prints a heartbeat on the serial port and blinks ``LED_BUILTIN``
only if the board's core defines it: no pin is assumed.
"""

from __future__ import annotations

from typing import Dict

from .boards import ARDUINO_CLI, ESP_IDF, MAKE, PLATFORMIO
from .model import Project

LOGIC_H = """\
// Plain C++ logic with no hardware access: it can be unit tested on a computer.
#pragma once
#include <stdint.h>

// True when `period` milliseconds have passed since `last` (handles millis() wrap-around).
inline bool app_is_due(uint32_t now, uint32_t last, uint32_t period) {
  return (uint32_t)(now - last) >= period;
}
"""

ARDUINO_MAIN = """\
// {name}: starter firmware generated by mCode Studio for {board}.
//
// It prints a heartbeat on the serial port every second and blinks
// LED_BUILTIN when the board's core defines one. No other pin is assumed:
// check your board's documentation before wiring anything, and record the
// wiring in docs/WIRING.md.
{include}#include "app_logic.h"

static const uint32_t SERIAL_BAUD = {baud};
static const uint32_t BEAT_MS = 1000;
static uint32_t lastBeat = 0;
static uint32_t beats = 0;

void setup() {{
  Serial.begin(SERIAL_BAUD);
#ifdef LED_BUILTIN
  pinMode(LED_BUILTIN, OUTPUT);
#endif
  delay(200);
  Serial.println(F("{name}: ready"));
}}

void loop() {{
  uint32_t now = millis();
  if (app_is_due(now, lastBeat, BEAT_MS)) {{
    lastBeat = now;
    beats++;
#ifdef LED_BUILTIN
    digitalWrite(LED_BUILTIN, (beats & 1) ? HIGH : LOW);
#endif
    Serial.print(F("heartbeat "));
    Serial.println(beats);
  }}
}}
"""

PIO_TEST = """\
// Host-side unit tests: `pio test -e native` (no board needed).
#include <unity.h>
#include "app_logic.h"

void setUp(void) {}
void tearDown(void) {}

static void test_due_after_period(void) {
  TEST_ASSERT_TRUE(app_is_due(2000, 1000, 1000));
  TEST_ASSERT_FALSE(app_is_due(1999, 1000, 1000));
}

static void test_due_across_wraparound(void) {
  TEST_ASSERT_TRUE(app_is_due(500, 0xFFFFFF00u, 700));
}

int main(int argc, char **argv) {
  (void)argc;
  (void)argv;
  UNITY_BEGIN();
  RUN_TEST(test_due_after_period);
  RUN_TEST(test_due_across_wraparound);
  return UNITY_END();
}
"""

IDF_MAIN = """\
// {name}: starter firmware generated by mCode Studio for {board} (ESP-IDF).
// It logs a heartbeat every second. No pin is assumed: record your wiring
// in docs/WIRING.md.
#include <stdio.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_log.h"

static const char *TAG = "app";

void app_main(void)
{{
    unsigned beats = 0;
    ESP_LOGI(TAG, "{name}: ready");
    while (1) {{
        ESP_LOGI(TAG, "heartbeat %u", ++beats);
        vTaskDelay(pdMS_TO_TICKS(1000));
    }}
}}
"""

MAKEFILE = """\
# {name}: a plain C project generated by mCode Studio.
# `make` builds, `make test` runs the unit tests, `make clean` removes output.
# For a microcontroller, set CC (e.g. arm-none-eabi-gcc) and add your own
# flash target; mCode runs `make`, `make clean` and `make test`.
CC ?= cc
CFLAGS ?= -std=c11 -Wall -Wextra -O2 -Iinclude
BUILD := build

all: $(BUILD)/app

$(BUILD)/app: src/main.c src/logic.c include/logic.h | $(BUILD)
\t$(CC) $(CFLAGS) -o $@ src/main.c src/logic.c

$(BUILD)/test_logic: test/test_logic.c src/logic.c include/logic.h | $(BUILD)
\t$(CC) $(CFLAGS) -o $@ test/test_logic.c src/logic.c

test: $(BUILD)/test_logic
\t./$(BUILD)/test_logic

$(BUILD):
\tmkdir -p $(BUILD)

clean:
\trm -rf $(BUILD)

.PHONY: all test clean
"""

MAKE_MAIN = """\
#include <stdio.h>
#include "logic.h"

int main(void)
{
    printf("{name}: 3 + 4 = %d\\n", logic_add(3, 4));
    return 0;
}
"""

MAKE_LOGIC_H = """\
#pragma once
int logic_add(int a, int b);
"""

MAKE_LOGIC_C = """\
#include "logic.h"

int logic_add(int a, int b)
{
    return a + b;
}
"""

MAKE_TEST = """\
#include <stdio.h>
#include "logic.h"

static int failures = 0;
#define CHECK(cond) do { if (!(cond)) { printf("FAIL %s:%d %s\\n", __FILE__, __LINE__, #cond); failures++; } } while (0)

int main(void)
{
    CHECK(logic_add(2, 2) == 4);
    CHECK(logic_add(-1, 1) == 0);
    if (failures)
        printf("%d test(s) failed\\n", failures);
    else
        printf("all tests passed\\n");
    return failures ? 1 : 0;
}
"""

WIRING = """\
# Wiring — {name}

Board: **{board}** ({mcu}).

| Signal | Board pin | Connected to | Voltage | Source |
|---|---|---|---|---|
| (none yet) | | | | |

Rules for this table (also given to the AI Engineer):

- Fill in a pin only from the board's documentation or your own measurement,
  and write that source in the last column.
- Mark anything not checked against a datasheet as **assumption**.
- Note the logic level (3.3 V or 5 V) of every connection; ESP32 pins are not
  5 V tolerant.
"""

GITIGNORE = """\
.pio/
build/
.mcode/build/
.mcode/ai/
managed_components/
sdkconfig.old
"""


def _readme(project: Project, build: str, test: str) -> str:
    return f"""\
# {project.name}

Created with mCode Studio for **{project.board_name}** ({project.mcu}) using
{_tool_name(project)}.

| | |
|---|---|
| Build | {build} |
| Tests | {test} |
| Wiring | [docs/WIRING.md](docs/WIRING.md) |

Upload from mCode (Build → Flash). mCode checks the board and port and asks
before anything is written to the board.
"""


def _tool_name(project: Project) -> str:
    return {ARDUINO_CLI: "the Arduino CLI", PLATFORMIO: "PlatformIO", ESP_IDF: "ESP-IDF",
            MAKE: "Make"}.get(project.toolchain, project.toolchain)


def files_for(project: Project) -> Dict[str, str]:
    """{relative path: content} for a new project."""
    board = project.board
    if board is None:
        raise ValueError(f"unknown board {project.board_id}")
    fmt = {"name": project.name, "board": board.name, "mcu": board.mcu, "baud": project.baud}
    files: Dict[str, str] = {
        "docs/WIRING.md": WIRING.format(**fmt),
        ".gitignore": GITIGNORE,
    }
    if project.toolchain == ARDUINO_CLI:
        files[f"{project.slug}.ino"] = ARDUINO_MAIN.format(include="", **fmt)
        files["app_logic.h"] = LOGIC_H
        files["sketch.yaml"] = (f"# Arduino CLI sketch project file (generated by mCode Studio)\n"
                                f"default_fqbn: {project.fqbn()}\n")
        files["README.md"] = _readme(project, f"`arduino-cli compile --fqbn {project.fqbn()} .`",
                                     "compile check (Build & Test)")
    elif project.toolchain == PLATFORMIO:
        env = project.pio_env or board.pio_board
        framework = project.framework
        lines = ["; PlatformIO project generated by mCode Studio", "[platformio]",
                 f"default_envs = {env}", "", f"[env:{env}]", f"platform = {board.pio_platform}",
                 f"board = {board.pio_board}", f"framework = {framework}",
                 f"monitor_speed = {project.baud}"]
        if project.upload_speed:
            lines.append(f"upload_speed = {project.upload_speed}")
        if project.usb_cdc_on_boot and board.native_usb and framework == "arduino":
            lines += ["build_flags =", "    -DARDUINO_USB_CDC_ON_BOOT=1"]
        lines.append("lib_deps =")
        lines += [f"    {lib}" for lib in project.libraries]
        if framework == "arduino":
            lines += ["", "; Unit tests on this computer: pio test -e native",
                      "[env:native]", "platform = native", "test_build_src = no"]
            files["src/main.cpp"] = ARDUINO_MAIN.format(include="#include <Arduino.h>\n", **fmt)
            files["lib/app_logic/app_logic.h"] = LOGIC_H
            files["test/test_app_logic/test_main.cpp"] = PIO_TEST
        else:
            files["src/main.c"] = IDF_MAIN.format(**fmt)
            files["src/CMakeLists.txt"] = 'idf_component_register(SRCS "main.c" INCLUDE_DIRS ".")\n'
            files["CMakeLists.txt"] = ("cmake_minimum_required(VERSION 3.16.0)\n"
                                       "include($ENV{IDF_PATH}/tools/cmake/project.cmake)\n"
                                       f"project({project.slug.replace('-', '_')})\n")
        files["platformio.ini"] = "\n".join(lines) + "\n"
        files["include/README"] = "Project header files (.h) go here.\n"
        files["lib/README"] = "Project-private libraries go here, one folder each.\n"
        test = "`pio test -e native` (on this computer)" if framework == "arduino" else \
            "on the board (ESP-IDF Unity tests)"
        files["README.md"] = _readme(project, f"`pio run -e {env}`", test)
    elif project.toolchain == ESP_IDF:
        files["CMakeLists.txt"] = ("cmake_minimum_required(VERSION 3.16)\n"
                                   "include($ENV{IDF_PATH}/tools/cmake/project.cmake)\n"
                                   f"project({project.slug.replace('-', '_')})\n")
        files["main/CMakeLists.txt"] = 'idf_component_register(SRCS "main.c" INCLUDE_DIRS ".")\n'
        files["main/main.c"] = IDF_MAIN.format(**fmt)
        files["sdkconfig.defaults"] = ("# Project defaults (generated by mCode Studio).\n"
                                       "CONFIG_ESPTOOLPY_FLASHSIZE_4MB=y\n")
        files["README.md"] = _readme(project, f"`idf.py set-target {board.idf_target}` then "
                                     "`idf.py build`", "on the board (Unity component tests)")
    elif project.toolchain == MAKE:
        files["Makefile"] = MAKEFILE.format(**fmt)
        files["src/main.c"] = MAKE_MAIN.replace("{name}", project.name)
        files["src/logic.c"] = MAKE_LOGIC_C
        files["include/logic.h"] = MAKE_LOGIC_H
        files["test/test_logic.c"] = MAKE_TEST
        files["README.md"] = _readme(project, "`make`", "`make test`")
    else:
        raise ValueError(f"unknown toolchain {project.toolchain}")
    return files
